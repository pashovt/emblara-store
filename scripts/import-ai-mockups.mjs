// Imports the owner's AI model mockups (06-AI-Models/Product-Mockups) into the
// store. Run from the project root: node scripts/import-ai-mockups.mjs
//
// For every row of image-index.csv:
//   variant "emblara" -> public/garments/<product>/<colour>-ai-front-emblara.webp
//                        (EMBLARA logo baked in; shown when the visitor has not
//                        added their own logo)
//   variant "blank"   -> public/garments/<product>/<colour>-ai-front.webp
//                        (no logo; the site draws any logo on top)
// "your-logo" placeholder images are not used on the site.
//
// The 1024 x 1536 portraits are widened to a square by extending the plain
// studio backdrop (blurred edge pixels), then scaled to 1000 x 1000, so they share
// the same square frame as the Gelato photos and the logo placement maths.
import { mkdir, readFile, access, writeFile } from 'node:fs/promises';
import sharp from 'sharp';

const ROOT = '../../../06-AI-Models/Product-Mockups/2026-10-09-Gelato/';
const SLUG = {
  SOLS11346: 'mens-polo',
  SOLS11347: 'womens-polo',
  SOLS03566: 'organic-polo',
  SOLS11362: 'printed-polo',
  G5000: 'heavy-cotton-tee',
  G2000: 'ultra-cotton-tee',
  G18500: 'logo-hoodie',
  G18000: 'crew-sweatshirt',
};
const kebab = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-');

const csv = (await readFile(`${ROOT}image-index.csv`, 'utf8')).trim().split('\n');
const head = csv.shift().split(',');
const rows = csv.map((line) => Object.fromEntries(line.split(',').map((v, i) => [head[i], v])));

// What each shot shows, in the store's own terms.
const METHOD = (m) => (/embroider/i.test(m) ? 'embroidery' : 'print');
const POSITION = (p) => (/left chest/i.test(p) && !/front/i.test(p) ? 'Left chest' : /left chest|front/i.test(p) ? 'Front' : p);

// Blank (no-logo) shots are looked for next to the others as <name>-blank.png.
const exists = (p) => access(p).then(() => true, () => false);
const jobs = [];
const shots = {};
for (const r of rows) {
  if (r.variant !== 'emblara') continue;
  const slug = SLUG[r.product_id];
  const colour = kebab(r.colour);
  const emblara = `/garments/${slug}/${colour}-ai-front-emblara.webp`;
  jobs.push([`${ROOT}${r.file}`, `public${emblara}`]);
  const blankSrc = `${ROOT}${r.file.replace('-emblara.png', '-blank.png')}`;
  const blank = (await exists(blankSrc)) ? `/garments/${slug}/${colour}-ai-front.webp` : null;
  if (blank) jobs.push([blankSrc, `public${blank}`]);
  shots[slug] = { colour: r.colour, method: METHOD(r.method), position: POSITION(r.placement), model: r.model_id, emblara, blank };
}
// Read by src/data/products.js. Regenerated by this script; do not edit by hand.
await writeFile('src/data/ai-shots.json', JSON.stringify(shots, null, 2) + '\n');

for (const [src, out] of jobs) {
  await mkdir(out.slice(0, out.lastIndexOf('/')), { recursive: true });
  const { width, height } = await sharp(src).metadata();
  const pad = Math.max(0, Math.round((height - width) / 2));
  // Side bands: the edge pixels stretched outwards and blurred, so the plain
  // studio backdrop continues without streaks. The photo sits on top, untouched.
  const bands = await sharp(src).extend({ left: pad, right: pad, extendWith: 'copy' }).blur(30).toBuffer();
  const square = await sharp(bands).composite([{ input: src, left: pad, top: 0 }]).toBuffer();
  await sharp(square)
    .resize(1000, 1000)
    .webp({ quality: 84 })
    .toFile(out);
  console.log('ok', out);
}
console.log(`${jobs.length} images`);
